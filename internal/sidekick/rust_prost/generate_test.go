func TestCopyCargoLock(t *testing.T) {
	for _, test := range []struct {
		name        string
		lockContent string
		wantExists  bool
	}{
		{
			name:        "copies existing Cargo.lock",
			lockContent: "# This file is automatically @generated by Cargo.\nversion = 4\n",
			wantExists:  true,
		},
		{
			name:       "ignores missing Cargo.lock",
			wantExists: false,
		},
	} {
		t.Run(test.name, func(t *testing.T) {
			workDir := t.TempDir()
			t.Chdir(workDir)
			if test.wantExists {
				if err := os.WriteFile("Cargo.lock", []byte(test.lockContent), 0o644); err != nil {
					t.Fatal(err)
				}
			}
			tmpDir := t.TempDir()
			if err := copyCargoLock(tmpDir); err != nil {
				t.Fatalf("copyCargoLock() unexpected error: %v", err)
			}
			got, err := os.ReadFile(filepath.Join(tmpDir, "Cargo.lock"))
			if !test.wantExists {
				if !errors.Is(err, fs.ErrNotExist) {
					t.Fatalf("expected ErrNotExist, got %v", err)
				}
				return
			}
			if err != nil {
				t.Fatal(err)
			}
			if diff := cmp.Diff(test.lockContent, string(got)); diff != "" {
				t.Errorf("Cargo.lock content mismatch (-want +got):\n%s", diff)
			}
		})
	}
}

func TestCopyCargoLock_Error(t *testing.T) {
	workDir := t.TempDir()
	t.Chdir(workDir)
	if err := os.WriteFile("Cargo.lock", []byte("version = 4\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	nonExistentDir := filepath.Join(t.TempDir(), "nonexistent")
	if err := copyCargoLock(nonExistentDir); err == nil {
		t.Fatal("copyCargoLock() expected error for nonexistent destination dir, got nil")
	}
}

